openApiGenerate {
    generatorName.set("kotlin")
    inputSpec.set(generatorSpec.get().asFile.absolutePath)
    outputDir.set(openApiOutput.get().asFile.absolutePath)
    cleanupOutput.set(true)
    packageName.set("com.classicchess.api")
    modelPackage.set("com.classicchess.api")
    // Component and inline response models only; operations are hand-written.
    globalProperties.set(mapOf("models" to "", "modelDocs" to "false", "modelTests" to "false"))
    // Skips request/response bodies declared inline on operations, and the
    // Lichess explorer passthrough that is served as a JsonObject below.
    ignoreFileOverride.set(file("openapi-generator-ignore").absolutePath)
    configOptions.set(mapOf(
        "serializationLibrary" to "kotlinx_serialization",
        "sourceFolder" to "src/main/kotlin",
        "dateLibrary" to "string",
        "enumPropertyNaming" to "UPPERCASE",
    ))
    // A value added to an API enum decodes as UNKNOWN_DEFAULT_OPEN_API
    // instead of failing every older client.
    additionalProperties.set(mapOf("enumUnknownDefaultCase" to "true"))
    // Wire types every kotlinx.serialization consumer can decode without a
    // contextual serializer; untyped `{}` schemas and the `type: null` items
    // of always-empty arrays become JSON.
    typeMappings.set(mapOf(
        "integer" to "kotlin.Long",
        "number" to "kotlin.Double",
        "URI" to "kotlin.String",
        "UUID" to "kotlin.String",
        "AnyType" to "JsonElement",
        "null" to "JsonElement",
    ))
    importMappings.set(mapOf(
        "JsonElement" to "kotlinx.serialization.json.JsonElement",
        "JsonObject" to "kotlinx.serialization.json.JsonObject",
    ))
    // The Kotlin generator folds an anyOf of several shapes into one class
    // whose fields are all required, so those unions stay JSON for callers to
    // inspect. It also cannot emit the Lichess explorer passthrough's
    // object-with-extra-properties members.
    schemaMappings.set(mapOf(
        "LichessOpeningExplorer" to "JsonObject",
        "PublicEventAbout_crosstable" to "JsonElement",
        "SiteSearchPage_results" to "JsonElement",
    ))
    nameMappings.set(mapOf("entries" to "entries"))
    inlineSchemaOptions.set(mapOf("ARRAY_ITEM_SUFFIX" to "Item", "SKIP_SCHEMA_REUSE" to "true"))
    inlineSchemaNameMappings.set(mapOf(
        "AnnotatedGame_allOf_annotation" to "AnnotatedGameAnnotation",
        "AnnotatedGame_allOf_annotation_notes" to "AnnotatedGameAnnotationNotesItem",
        "AnnotatedGame_allOf_book" to "AnnotatedGameBook",
        "PublicPlayer_allOf_archive_bucket" to "PublicPlayerArchiveBucket",
        "PublicPlayer_allOf_portrait" to "PublicPlayerPortrait",
    ))
}
val generatedModelSource = openApiOutput.map { it.dir("src/main/kotlin/$generatedModelPackageDir") }
// The generator's templates leave trailing spaces and blank last lines, which
// the repository whitespace gate rejects in committed sources.
fun tidyGeneratedSource(text: String) = text.lines().joinToString("\n") { it.trimEnd() }.trimEnd() + "\n"
val generateModels = tasks.register<Sync>("generateModels") {
    dependsOn(tasks.openApiGenerate)
    from(generatedModelSource)
    into("$generatedModelRoot/$generatedModelPackageDir")
    doLast {
        destinationDir.walkTopDown().filter { it.isFile }.forEach { it.writeText(tidyGeneratedSource(it.readText())) }
    }
}
// Builds read the committed models; `generateModels test` refreshes them first.
tasks.compileKotlin { mustRunAfter(generateModels) }
tasks.named("sourcesJar") { mustRunAfter(generateModels) }
val checkContract = tasks.register("checkContract") {
    dependsOn(tasks.openApiGenerate)
    val expectedDir = generatedModelSource.map { it.asFile }
    val committedDir = file("$generatedModelRoot/$generatedModelPackageDir")
    doLast {
        fun contents(dir: File, read: (File) -> String) = dir.walkTopDown().filter { it.isFile }
            .associate { it.relativeTo(dir).invariantSeparatorsPath to read(it) }
        val expected = contents(expectedDir.get()) { tidyGeneratedSource(it.readText()) }
        val committed = if (committedDir.isDirectory) contents(committedDir) { it.readText() } else emptyMap()
        val drift = (expected.keys + committed.keys).filter { expected[it] != committed[it] }.sorted()
        if (drift.isNotEmpty()) {
            throw GradleException(
                "Kotlin models differ from OpenAPI (${drift.joinToString()}); run ./gradlew generateModels.",
            )
        }
    }
}
