// openapi-generator 7.25's OpenAPI 3.1 support is beta: an allOf model loses
// the nullability of its members' 3.1 `type: [T, "null"]` and `anyOf` null
// fields, and `const` fields become untyped. The generator therefore reads the
// same contract written in 3.0 terms (`nullable`, plain types).
fun downlevelSchemaKeywords(node: JsonNode, parentKey: String? = null) {
    // Example and literal values are data, not schemas.
    if (parentKey in setOf("example", "examples", "default", "enum", "const")) return
    // Keys of these maps are names (a property may be called `default`).
    val names = parentKey in setOf("properties", "schemas", "paths", "responses", "content", "headers")
    node.fields().forEach { (key, child) -> downlevelSchemaKeywords(child, if (names) null else key) }
    if (node is ArrayNode) node.forEach { downlevelSchemaKeywords(it, parentKey) }
    if (node !is ObjectNode || names) return
    (node.get("type") as? ArrayNode)?.let { types ->
        val kinds = types.map { it.asText() }
        val concrete = kinds - "null"
        if ("null" in kinds) node.put("nullable", true)
        if (concrete.size == 1) node.put("type", concrete.single()) else node.remove("type")
    }
    for (keyword in listOf("anyOf", "oneOf")) {
        val members = node.get(keyword) as? ArrayNode ?: continue
        val concrete = members.filterNot { it.size() == 1 && it.path("type").asText() == "null" }
        if (concrete.size == members.size()) continue
        node.put("nullable", true)
        node.remove(keyword)
        val only = concrete.singleOrNull()
        when {
            only == null -> node.putArray(keyword).addAll(concrete)
            only.has("\$ref") -> node.putArray("allOf").add(only)
            else -> only.fields().forEach { (key, value) -> if (!node.has(key)) node.set<JsonNode>(key, value) }
        }
    }
    (node.get("enum") as? ArrayNode)?.let { values ->
        val concrete = values.filterNot { it.isNull }
        if (concrete.size != values.size()) {
            node.put("nullable", true)
            node.putArray("enum").addAll(concrete)
        }
    }
    node.remove("const")?.let { value ->
        if (!node.has("type")) {
            node.put("type", when {
                value.isTextual -> "string"
                value.isBoolean -> "boolean"
                value.isIntegralNumber -> "integer"
                value.isNumber -> "number"
                else -> "object"
            })
        }
    }
}
val downlevelOpenApi = tasks.register("downlevelOpenApi") {
    inputs.file(openApiSpec)
    outputs.file(generatorSpec)
    doLast {
        val contract = ObjectMapper(YAMLFactory()).readTree(openApiSpec) as ObjectNode
        contract.put("openapi", "3.0.3")
        downlevelSchemaKeywords(contract)
        generatorSpec.get().asFile.apply { parentFile.mkdirs() }
            .writeText(ObjectMapper().writerWithDefaultPrettyPrinter().writeValueAsString(contract))
    }
}

